const HEADER_FILL = 'FF154A91';

type Column = { header: string; key: string; width: number };

function sheet(workbook: ExcelJS.Workbook, name: string, columns: Column[]) {
  const ws = workbook.addWorksheet(name, {
    views: [{ state: 'frozen', ySplit: 1 }],
  });
  ws.columns = columns;

  const header = ws.getRow(1);
  header.font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 10 };
  header.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_FILL } };
  header.alignment = { vertical: 'middle' };
  header.height = 22;

  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: columns.length } };
  return ws;
}

function meta(workbook: ExcelJS.Workbook, user: SessionUser, title: string, notes: string[]) {
  const ws = workbook.addWorksheet('About', { views: [{ showGridLines: false }] });
  ws.columns = [{ width: 26 }, { width: 90 }];
  ws.addRow([title]).font = { bold: true, size: 14 };
  ws.addRow([]);
  ws.addRow(['Organization', user.organizationName]);
  ws.addRow(['Generated by', `${user.name} (${user.email})`]);
  ws.addRow(['Generated at', new Date().toISOString()]);
  ws.addRow(['Scope', 'Only branches this user is permitted to see are included.']);
  ws.addRow([]);
  for (const note of notes) ws.addRow(['', note]);
  ws.getColumn(1).font = { bold: true, size: 10 };
  return ws;
}

async function toBuffer(workbook: ExcelJS.Workbook) {
  const data = await workbook.xlsx.writeBuffer();
  return Buffer.from(data);
}

